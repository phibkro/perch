import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { OmpRemoteBridge } from './bridge.mjs';
import { attachRemoteExtension } from './extension.ts';
import { parseRemoteCatalog, parseRemoteSnapshot, parseRemoteReceipt } from '../../src/harness/remote.ts';
import { CONFIG, post, request, until } from './test/helpers.mjs';
import { CaptureTerminal } from './test/capture-terminal.mjs';

// The production extension has no OMP runtime dependency. This opt-in verifier
// installs the actual SDK separately and substitutes only the model stream.
const runtime = resolve(process.env.PERCH_OMP_RUNTIME || fileURLToPath(new URL('./upstream', import.meta.url)));
const load = name => import(Bun.resolveSync(name, runtime));
const sdkPath = Bun.resolveSync('@oh-my-pi/pi-coding-agent/sdk', runtime);
const packageVersion = JSON.parse(readFileSync(join(dirname(dirname(sdkPath)), 'package.json'), 'utf8')).version;
assert.equal(packageVersion, '18.8.7', 'Run this verifier against the pinned OMP release.');
assert.ok(process.argv.slice(2).every(value => value === '--interactive'), 'Only --interactive is supported.');
const interactive = process.argv.includes('--interactive');
const directory = mkdtempSync(join(tmpdir(), 'perch-omp-remote-'));
process.env.PI_CODING_AGENT_DIR = directory;
process.env.PI_TEST_RUNTIME = '1';
const [{ createAgentSession }, { AuthStorage }, { SessionManager }, { ModelRegistry }, { Settings },
  { createMockModel }, { getBundledModel }, { initializeExtensions }] = await Promise.all([
  load('@oh-my-pi/pi-coding-agent/sdk'), load('@oh-my-pi/pi-coding-agent/session/auth-storage'),
  load('@oh-my-pi/pi-coding-agent/session/session-manager'), load('@oh-my-pi/pi-coding-agent/config/model-registry'),
  load('@oh-my-pi/pi-coding-agent/config/settings'), load('@oh-my-pi/pi-ai/providers/mock'),
  load('@oh-my-pi/pi-catalog/models'), load('@oh-my-pi/pi-coding-agent/modes/runtime-init'),
]);

const errors = [], checks = [];
let session, authStorage, bridge, mode, terminal;
try {
  authStorage = await AuthStorage.create(join(directory, 'auth.db'));
  authStorage.keys.setRuntime('openai', 'local-fixture-key-not-a-provider-credential');
  const model = getBundledModel('openai', 'gpt-4o-mini');
  assert.ok(model, 'The pinned catalog must include the fixture model.');
  const mock = createMockModel({ responses: [
    { content: ['Existing host answer'] },
    { content: ['# Remote answer\n\nGenerated by the deterministic upstream test provider.'] },
    { delayMs: 3000, content: ['This delayed answer must be interrupted.'] },
    { content: ['The same host process resumed after phone reconnection.'] },
  ] });
  const created = await createAgentSession({ cwd: directory, agentDir: directory, authStorage,
    modelRegistry: new ModelRegistry(authStorage, join(directory, 'models.yml')), model,
    settings: Settings.isolated({ 'compaction.enabled': false, 'retry.maxRetries': 0 }),
    sessionManager: SessionManager.inMemory(directory), disableExtensionDiscovery: true,
    extensions: [api => { bridge = new OmpRemoteBridge(api, CONFIG, { allowEphemeralPort: true }); attachRemoteExtension(api, bridge); }],
    skills: [], contextFiles: [], promptTemplates: [], slashCommands: [], rules: [], preloadedCustomToolPaths: [],
    enableMCP: false, enableLsp: false, skipPythonPreflight: true, cacheWarming: false, toolNames: [] });
  session = created.session;
  session.agent.streamFn = mock.stream;
  if (interactive) {
    const [{ InteractiveMode }, { Composer }, { initTheme }] = await Promise.all([
      load('@oh-my-pi/pi-coding-agent/modes/interactive-mode'), load('@oh-my-pi/pi-tui/prompt/composer'), load('@oh-my-pi/pi-tui/theme')]);
    await Settings.init({ inMemory: true, cwd: directory });
    initTheme();
    terminal = new CaptureTerminal();
    const composer = new Composer({ terminal });
    mode = new InteractiveMode(session, packageVersion, undefined, created.setToolUIContext, undefined, undefined, undefined, composer);
    await mode.init({ suppressWelcomeIntro: true, autoStartCollab: false });
  } else {
    await initializeExtensions(session, { reportSendError: (action, failure) => errors.push({ action, error: failure.message }),
      reportRuntimeError: failure => errors.push({ action: 'extension', error: failure.message }) });
  }
  assert.ok(bridge.url);
  const address = bridge.url;
  const path = '/perch/sessions/omp_test';
  const get = async route => (await request(address, route)).json();
  const snapshot = async () => parseRemoteSnapshot(await get(path));
  const command = (id, type, extra = {}) => {
    const current = bridge.catalog().sessions[0];
    return { id, epoch: bridge.epoch, generation: current.generation, conversationId: current.conversationId, type, ...extra };
  };
  const send = async value => parseRemoteReceipt(await (await request(address, `${path}/commands`, post(value))).json());
  const originalSession = session, originalPid = process.pid;

  await session.prompt('A prompt submitted by the host before the phone attaches.');
  const initial = await snapshot();
  assert.equal(initial.session.conversationId, session.sessionManager.getSessionId());
  assert.equal(initial.session.pid, originalPid);
  assert.equal(initial.messages.at(-1).text, 'Existing host answer');
  checks.push('An authenticated snapshot exposes existing real OMP history from its current session manager.');

  const prompt = command('phone_prompt', 'prompt', { text: 'A prompt from the attached phone.' });
  assert.equal((await send(prompt)).status, 'forwarded');
  await until(() => mock.calls.length === 2 && !session.isStreaming && bridge.snapshot().messages.at(-1)?.text.includes('# Remote answer'), 5000);
  const answered = await snapshot();
  assert.equal(answered.messages.filter(message => message.text === prompt.text).length, 1);
  assert.ok(answered.messages.at(-1).text.includes('# Remote answer'));
  assert.equal(answered.capabilities.prompt, true);
  assert.equal((await send(prompt)).status, 'forwarded');
  assert.equal(mock.calls.length, 2);
  checks.push('Public sendUserMessage reaches the same AgentSession exactly once within this receipt epoch.');
  if (terminal) {
    await until(() => Bun.stripANSI(terminal.output).includes('Remote answer'), 5000);
    checks.push('The real stock InteractiveMode and its extension UI controller render the phone-originated answer into captured terminal output.');
  }

  await get('/perch/health'); await get('/perch/sessions'); await get(path); await get(`${path}/operations/phone_prompt`);
  assert.equal(mock.calls.length, 2); assert.equal(session, originalSession); assert.equal(process.pid, originalPid);
  checks.push('Phone reconnection reads do not restart OMP or replay a submitted prompt.');

  const slow = command('slow_prompt', 'prompt', { text: 'Keep working while the phone is disconnected.' });
  assert.equal((await send(slow)).status, 'forwarded');
  await until(() => mock.calls.length === 3 && session.isStreaming, 5000);
  assert.equal((await snapshot()).session.status, 'working');
  assert.equal((await send(command('interrupt_prompt', 'interrupt'))).status, 'forwarded');
  await until(() => !session.isStreaming, 5000);
  const aborted = session.sessionManager.getBranch().filter(entry => entry.type === 'message' && entry.message.role === 'assistant').at(-1);
  assert.equal(aborted.message.stopReason, 'aborted');
  assert.equal(session, originalSession); assert.ok(bridge.url);
  checks.push('Public abort interrupts the active real OMP turn and leaves the process and adapter alive.');

  const alternate = (await snapshot()).availableModels.find(candidate => candidate.provider === 'openai' && candidate.id === 'gpt-4o');
  assert.ok(alternate, 'The fixture credential should advertise the second pinned model.');
  assert.equal((await send(command('change_model', 'set-model', { provider: alternate.provider, modelId: alternate.id }))).status, 'forwarded');
  assert.equal((await snapshot()).session.model.id, alternate.id);
  checks.push('Public model selection updates the same host session using host-side model metadata.');

  assert.equal((await send(command('after_reconnect', 'prompt', { text: 'Continue from the same host history.' }))).status, 'forwarded');
  await until(() => mock.calls.length === 4 && !session.isStreaming, 5000);
  assert.equal((await snapshot()).messages.at(-1).text, 'The same host process resumed after phone reconnection.');
  const stale = command('stale_after_new', 'prompt', { text: 'Must not enter a different conversation.' });
  await session.newSession();
  const fresh = parseRemoteCatalog(await get('/perch/sessions'));
  assert.notEqual(fresh.sessions[0].conversationId, stale.conversationId);
  assert.notEqual(fresh.sessions[0].generation, stale.generation);
  assert.equal(fresh.epoch, stale.epoch); assert.equal(bridge.url, address);
  assert.equal((await send(stale)).status, 'rejected'); assert.equal(mock.calls.length, 4);
  checks.push('A real host /new transition retains the adapter and rejects stale conversation commands.');

  assert.deepEqual(errors, []);
  mode?.stop(); mode = undefined;
  await session.dispose(); session = undefined;
  assert.equal(bridge.url, undefined);
  checks.push('The public session_shutdown event closes the extension listener on real host disposal.');
  console.log(JSON.stringify({ verified: true, ompVersion: packageVersion, pid: originalPid, agentSessionsCreated: 1,
    modelCalls: mock.calls.length, paidProviderCalls: 0,
    mode: interactive ? 'Real stock InteractiveMode over one SDK session with a captured terminal and the upstream in-memory mock provider; no physical terminal, Tern, phone, or live provider.'
      : 'Real upstream SDK session and extension runner with the upstream in-memory mock provider; no InteractiveMode, Tern, phone, or live provider.', checks }, null, 2));
} finally {
  mode?.stop();
  await session?.dispose(); await bridge?.close(); authStorage?.close();
  rmSync(directory, { recursive: true, force: true });
}
